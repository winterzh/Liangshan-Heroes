"""Read-only original-byte and selected-view audit, not native qualification."""
import hashlib
import json
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / 'assets/characters/wu_yong_pushcart_sources_20261017/prompt_set.json'
DIRS = ('se', 'sw', 'ne', 'nw')
POSES = ('push_idle', 'push_contact_a', 'push_passing_a', 'push_contact_b', 'push_passing_b')


def sha(path):
    with path.open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def repo_path(name):
    relative = Path(name)
    assert not relative.is_absolute() and '..' not in relative.parts and '\\' not in name
    result = ROOT / relative
    assert result.resolve().is_relative_to(ROOT) and result.is_file() and not result.is_symlink()
    return result


def verify():
    manifest = json.loads(MANIFEST.read_text(encoding='utf-8'))
    rows = manifest['sources']
    indexed = {row['key']: row for row in rows}
    assert len(rows) == len(indexed) == 8 and len(manifest['selected_candidates']) == 5
    assert manifest['mode'] == 'builtin_imagegen' and not manifest['pixel_writes'] and not manifest['runtime_adopted']
    assert (MANIFEST.parent / '.gdignore').is_file() and set(manifest['view_bindings']) == set(POSES)
    checks, selected_views, geometry = [], [], {}
    original_available = 0

    def check(condition, name):
        checks.append({'name': name, 'passed': bool(condition)})
        assert condition, name

    for row in rows:
        path = repo_path(row['path'])
        check(sha(path) == row['sha256'] and path.stat().st_size == row['bytes'], 'original repository bytes ' + row['key'])
        original = Path(row['generated_path'])
        if original.is_file():
            check(sha(original) == row['sha256'], 'original generated bytes ' + row['key'])
            original_available += 1
        check(bool(row['prompt']) and bool(row['references']) and bool(row['review']), 'complete request and direct review ' + row['key'])
        for reference in row['references']:
            check(sha(repo_path(reference['repository_path'])) == reference['sha256'], 'reference ' + row['key'] + ' ' + reference['repository_path'])
        with Image.open(path) as image:
            check(image.mode == 'RGBA' and list(image.size) == row['geometry']['size'], 'RGBA dimensions ' + row['key'])
            alpha = np.asarray(image)[:, :, 3].copy()
        geometry[row['key']] = alpha
        corners = alpha[[0, 0, -1, -1], [0, -1, 0, -1]].tolist()
        check(corners == [0, 0, 0, 0] == row['geometry']['corner_alpha'], 'whole image zero alpha corners ' + row['key'])

    selected = set()
    for pose in POSES:
        bindings = manifest['view_bindings'][pose]
        check(set(bindings) == set(DIRS), 'four explicit directions ' + pose)
        for direction in DIRS:
            key = bindings[direction]
            selected.add(key)
            row, alpha = indexed[key], geometry[key]
            h, w = alpha.shape
            x, y, cw, ch = row['geometry']['cells'][direction]['region']
            sx, sy = row['geometry']['split']
            check(min(x, y) >= 0 and min(cw, ch) > 0 and x + cw <= w and y + ch <= h, 'view bounds ' + pose + direction)
            check(not np.any(alpha[:, sx] >= 16) and not np.any(alpha[sy, :] >= 16), 'strong alpha separated axes ' + pose + direction)
            corners = alpha[[y, y, y + ch - 1, y + ch - 1], [x, x + cw - 1, x, x + cw - 1]].tolist()
            check(corners == [0, 0, 0, 0] == row['geometry']['cells'][direction]['corner_alpha'], 'selected view zero corners ' + pose + direction)
            check(row['selected_candidate'] and direction in row['selected_directions'], 'selected authority ' + pose + direction)
            review = manifest['manual_view_review'][pose][direction]
            check(review['seen'] and review['source'] == key and bool(review['note']), 'recorded direct view review ' + pose + direction)
            selected_views.append({'pose': pose, 'direction': direction, 'source': key, 'region': [x, y, cw, ch]})
    check(selected == set(manifest['selected_candidates']), 'selected source inventory')
    return {'passed': True, 'checks': checks, 'sources': len(rows), 'selected_source_pngs': len(selected),
            'references': sum(len(row['references']) for row in rows), 'original_generated_files_available': original_available,
            'selected_views': selected_views, 'runtime_adopted': False, 'native_launched': False, 'pixel_writes': False,
            'scope': 'Source bytes, explicit views/corners/strong-alpha axis separation and recorded direct review only. Not native import/mipmaps, scale continuity, wheel rotation or runtime adoption.'}


if __name__ == '__main__':
    result = verify()
    print(json.dumps({key: value for key, value in result.items() if key not in ['checks', 'selected_views']}, ensure_ascii=False))
