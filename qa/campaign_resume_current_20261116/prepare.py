"""Freeze current campaign gameplay plus the reviewed resume overlay.

No production writes, cache seeding, old test qualification or public enablement.
The binary helper is supplied locally and checked against its build receipt.
Each cold import owns the caller's shared engine lock and a fresh private profile.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import shutil
import subprocess
import sys
import time
import uuid

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
FREEZE = ROOT / '.godot/campaign_resume_current_20261116'
sys.path.insert(0, str(ROOT / 'tools'))
import run_character_art_qa as common

shared, running = common.load_helpers(ROOT)
spec = importlib.util.spec_from_file_location(
    'resume_current_identity', ROOT / 'tools/contracts/run_content_identity_20260907/build_identity.py')
identity = importlib.util.module_from_spec(spec)
spec.loader.exec_module(identity)


def need(value, message):
    if not value:
        raise RuntimeError(message)


def digest(raw):
    return hashlib.sha256(raw).hexdigest()


def sha(path):
    with Path(path).open('rb') as handle:
        return hashlib.file_digest(handle, 'sha256').hexdigest()


def read(path):
    return json.loads(Path(path).read_text(encoding='utf-8'))


def save(path, value):
    with Path(path).open('x', encoding='utf-8') as handle:
        handle.write(json.dumps(value, ensure_ascii=False, indent=2) + '\n')


def inside(root, relative):
    need(identity.relative_ok(relative), 'Invalid relative path: ' + relative)
    result = Path(root).absolute() / relative
    identity.no_links(result)
    return result


def put(project, relative, raw):
    target = inside(project, relative)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(raw)
    need(target.read_bytes() == raw, 'Write changed: ' + relative)


def sources(native_root):
    contract = read(HERE / 'overlay.json')
    need(contract['schema'] == 'campaign_resume_current_composition_v1', 'Composition schema')
    need(contract['qualification_inherited'] is False, 'Never inherit qualification')
    need(len(contract['files']) == 26 and len(contract['uid_companions']) == 11
         and len(contract['native_assets']) == 1, 'Reviewed 26 + 11 + 1 scope')
    payload = {}
    for row in contract['files']:
        current = inside(ROOT, row['path'])
        actual = sha(current) if current.exists() else None
        need(actual == row['current_base_sha256'], 'Current overlay base changed: ' + row['path'])
        if row['source_kind'] == 'git_blob':
            raw = subprocess.check_output(
                ['git', 'show', contract['source_commit'] + ':' + row['source_path']], cwd=ROOT)
        else:
            need(row['source_kind'] == 'local_merged' and row['path'] == 'scripts/battle.gd', 'Only Battle merged')
            raw = inside(ROOT, row['source_path']).read_bytes()
        need(digest(raw) == row['candidate_sha256'] and len(raw) == row['candidate_bytes'], 'Overlay changed')
        payload[row['path']] = raw
    for row in contract['uid_companions']:
        raw = row['content'].encode('utf-8')
        need(digest(raw) == row['sha256'] and len(raw) == row['bytes'], 'UID changed')
        need(not inside(ROOT, row['path']).exists(), 'UID conflicts with production')
        payload[row['path']] = raw
    # First import exposed absent import sidecars; bind their generated bytes
    # before a new cold attempt. These are source metadata, never cached imports.
    need(len(contract['import_metadata']) == 13, 'Reviewed missing metadata scope')
    for row in contract['import_metadata']:
        raw = row['content'].encode('utf-8')
        need(row['path'].endswith(('.uid', '.png.import')), 'Only source import metadata')
        need(row['path'] not in payload and not inside(ROOT, row['path']).exists(), 'Metadata conflict')
        need(digest(raw) == row['sha256'] and len(raw) == row['bytes'], 'Import metadata changed')
        payload[row['path']] = raw
    native = contract['native_assets'][0]
    helper = inside(native_root, native['source_path'])
    build = helper.parent / 'build_receipt.json'
    need(sha(build) == native['build_receipt_sha256'], 'Native build receipt changed')
    receipt = read(build)
    need(receipt['complete'] and receipt['compiled'] and receipt['compiler_exit'] == 0, 'Native build incomplete')
    source = inside(native_root, 'qa/campaign_progress_recovery_20261026/process_liveness_candidate/native/ProcessLivenessProbe.cs')
    need(sha(source) == native['source_sha256'] == receipt['source_sha256'], 'Native source changed')
    raw = helper.read_bytes()
    need(digest(raw) == native['candidate_sha256'] == receipt['helper_sha256'], 'Native helper changed')
    payload[native['path']] = raw
    need(sha(HERE / 'battle_merge.patch') == contract['merge']['patch_sha256'], 'Review patch changed')
    pins = {str(path): sha(path) for path in [Path(__file__), HERE / 'overlay.json',
            HERE / 'battle_merge.patch', HERE / 'overlay/battle.gd', Path(common.__file__),
            Path(shared.__file__), Path(identity.__file__), ROOT / 'tools/run_campaign_level_state_qa.py', build, source, helper]}
    return contract, payload, pins


def check_pins(pins):
    for name, expected in pins.items():
        need(sha(name) == expected, 'Pinned source changed: ' + name)


def cold_inventory(project):
    cache = project / '.godot'
    expected = ('\n'.join(shared.NATIVE_BINDINGS) + '\n').encode('utf-8')
    need([p.name for p in cache.iterdir()] == ['extension_list.cfg'], 'Must start without old cache')
    raw = (cache / 'extension_list.cfg').read_bytes()
    # Shared Windows installer writes CRLF; this is fresh registration, not cache.
    need(raw.replace(b'\r\n', b'\n') == expected, 'Unexpected native registration')
    return {'cache_seeded': False, 'only_fresh_extension_registration': True,
            'bytes': len(raw), 'sha256': digest(raw)}


def prepare(native_root):
    contract, payload, pins = sources(native_root)
    run = FREEZE / (time.strftime('%Y%m%d_%H%M%S') + '_' + uuid.uuid4().hex[:8])
    project = run / 'project'
    project.mkdir(parents=True, exist_ok=False)
    receipt = {'schema': 'campaign_resume_current_preparation_v1', 'complete': False,
               'project': str(project), 'production_modified': False, 'cache_seeded': False,
               'qualification_inherited': False, 'native_root': str(native_root.absolute()),
               'pins': pins, 'runner_sha256': sha(__file__)}
    try:
        print('SNAPSHOT current gameplay inputs', flush=True)
        current = identity.snapshot(ROOT)
        save(run / 'root_source.json', current)
        expected = {row['path']: row for row in current['files']}
        for name, present in current['directories'].items():
            if present and not name.startswith('@file/'):
                inside(project, name).mkdir(parents=True, exist_ok=True)
        notice = time.monotonic()
        for index, row in enumerate(current['files'], 1):
            source, target = inside(ROOT, row['path']), inside(project, row['path'])
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(source, target)
            need(sha(target) == row['sha256'], 'Source copy changed: ' + row['path'])
            if time.monotonic() - notice > 25:
                print('COPY', index, '/', len(current['files']), flush=True)
                notice = time.monotonic()
        need(not (project / 'addons').exists(), 'Unexpected native inputs; review composition first')
        receipt['native_dependencies'] = shared.install_native(project)
        for path in sorted((project / 'addons').rglob('*')):
            if path.is_file():
                name = path.relative_to(project).as_posix()
                expected[name] = {'path': name, 'bytes': path.stat().st_size, 'sha256': sha(path)}
        for name, raw in payload.items():
            put(project, name, raw)
            expected[name] = {'path': name, 'bytes': len(raw), 'sha256': digest(raw)}
        receipt['identity_seed'] = identity.seed(project)
        save(run / 'cold_inventory.json', cold_inventory(project))
        print('VERIFY exact composed source', flush=True)
        composed = identity.snapshot(project)
        need(composed['files'] == [expected[k] for k in sorted(expected)], 'Composition mismatch')
        save(run / 'preimport_source.json', composed)
        save(run / 'candidate_manifest.json', contract)
        need(identity.snapshot(ROOT) == current, 'Current gameplay changed during freeze')
        check_pins(pins)
        receipt.update(complete=True, files=composed['file_count'], bytes=composed['total_bytes'],
                       preimport_sha256=sha(run / 'preimport_source.json'),
                       root_source_sha256=sha(run / 'root_source.json'),
                       manifest_sha256=sha(run / 'candidate_manifest.json'))
    except BaseException as error:
        receipt['error'] = repr(error)
    finally:
        save(run / 'preparation.json', receipt)
    print(json.dumps({'run': str(run), 'complete': receipt['complete'], 'error': receipt.get('error')}, ensure_ascii=False), flush=True)
    need(receipt['complete'], 'Candidate preparation failed')


def admission(run):
    run = run.absolute()
    identity.no_links(run)
    need(run.parent == FREEZE and run.is_dir(), 'Owned direct candidate directory required')
    receipt = read(run / 'preparation.json')
    need(receipt['complete'] and receipt['runner_sha256'] == sha(__file__), 'Preparation binding changed')
    check_pins(receipt['pins'])
    for name, key in [('root_source.json', 'root_source_sha256'), ('preimport_source.json', 'preimport_sha256'),
                      ('candidate_manifest.json', 'manifest_sha256')]:
        need(sha(run / name) == receipt[key], 'Prepared evidence changed')
    need(identity.snapshot(ROOT) == read(run / 'root_source.json'), 'Current gameplay changed; refreeze')
    return run, run / 'project', receipt


def import_cold(run, engine, lock):
    run, project, preparation = admission(run)
    need(not (run / 'cold_import').exists(), 'First cold import only; refreeze after a failed attempt')
    need(identity.snapshot(project) == read(run / 'preimport_source.json'), 'Prepared candidate changed')
    need((project / identity.DERIVED).read_bytes() == identity.STUB, 'Fresh identity stub required')
    need(not running(), 'Shared engine lane busy; no process started')
    output = run / 'cold_import'
    output.mkdir()
    receipt = {'schema': 'campaign_resume_current_cold_import_v1', 'complete': False,
               'cold_import_qualified': False, 'steps': [], 'runner_sha256': sha(__file__),
               'engine_sha256': sha(engine), 'preparation_sha256': sha(run / 'preparation.json')}
    locked = False
    try:
        with lock.open('x', encoding='utf-8') as handle:
            handle.write(str(output))
        locked = True
        need(not running(), 'Engine appeared before import')
        receipt['cold_before'] = cold_inventory(project)
        need(receipt['cold_before'] == read(run / 'cold_inventory.json'), 'Cold registration changed')
        profile = Path(ROOT.anchor) / 'CodexQA/resumecurrent' / uuid.uuid4().hex[:12]
        identity.no_links(profile)
        profile.mkdir(parents=True, exist_ok=False)
        env = common.private_environment(profile)
        for key in list(env):
            if key.startswith(('LSH_', 'LT_', 'LL_', 'CR_', 'RS_', 'DF_', 'HG_', 'GT_')):
                env.pop(key)
        env.update(STEAM_DISABLED='1', CAMPAIGN_QA='')
        receipt['profile'] = str(profile)
        common.process_step(engine, project, env, output, 'import',
                            ['--headless', '--editor', '--import', '--quit'], 1200,
                            'gl_compatibility', running, receipt['steps'])
        need(identity.snapshot(project) == read(run / 'preimport_source.json'), 'Cold import changed source or UID')
        generation = identity.generate(project)
        save(run / 'generation.json', generation)
        save(run / 'expected_identity.json', {k: v for k, v in generation['identity'].items() if k not in ('files', 'directories')})
        identity.verify_generated(project, generation)
        need(identity.snapshot(ROOT) == read(run / 'root_source.json'), 'Gameplay changed during import')
        check_pins(preparation['pins'])
        need(sha(engine) == receipt['engine_sha256'], 'Engine changed during import')
        receipt.update(complete=True, cold_import_qualified=True,
                       generation_sha256=sha(run / 'generation.json'), children_gone=not running())
    except BaseException as error:
        receipt['error'] = repr(error)
    finally:
        receipt['lock_released'] = bool(locked and common.release_owned_lock(lock, output, receipt, running()))
        save(output / 'receipt.json', receipt)
    print(json.dumps({'run': str(run), 'complete': receipt['complete'], 'error': receipt.get('error'),
                      'lock_released': receipt['lock_released']}, ensure_ascii=False), flush=True)
    need(receipt['complete'] and receipt['lock_released'], 'Cold import incomplete')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group()
    group.add_argument('--prepare', action='store_true')
    group.add_argument('--import-cold', type=Path)
    parser.add_argument('--native-root', type=Path)
    parser.add_argument('--godot', type=Path)
    parser.add_argument('--lock', type=Path)
    args = parser.parse_args()
    if args.import_cold:
        need(args.godot and args.lock and args.lock.is_absolute(), 'Explicit engine and shared lock required')
        import_cold(args.import_cold, args.godot.absolute(), args.lock)
    else:
        need(args.native_root and args.native_root.is_absolute(), 'Absolute local native source required')
        if args.prepare:
            prepare(args.native_root)
        else:
            contract, payload, pins = sources(args.native_root)
            print(json.dumps({'modules': len(contract['files']), 'uids': 11, 'native_helpers': 1,
                              'engine_started': False, 'writes': False, 'source_pins': len(pins)}))


if __name__ == '__main__':
    main()
